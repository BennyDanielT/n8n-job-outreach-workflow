"""Build the embedded font CSS and icon set used by the resume template.

Fonts: Latin Modern Roman (GUST Font License), the OpenType version of Computer Modern,
which is what pdflatex uses by default. Icons: Font Awesome Free (CC BY 4.0).

Usage:
  python scripts/build_assets.py --lm-dir /usr/share/texmf/fonts/opentype/public/lm \
      --fa-dir node_modules/@fortawesome/fontawesome-free/svgs
"""

import argparse
import base64
import io
import json
import re
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

OUT = Path(__file__).resolve().parents[1] / "app" / "templates" / "assets"

FACES = [
    # (css family, weight, style, file)
    ("LM Roman 10", 400, "normal", "lmroman10-regular.otf"),
    ("LM Roman 10", 700, "normal", "lmroman10-bold.otf"),
    ("LM Roman 10", 400, "italic", "lmroman10-italic.otf"),
    ("LM Roman 10", 700, "italic", "lmroman10-bolditalic.otf"),
    ("LM Roman 12", 400, "normal", "lmroman12-regular.otf"),
    ("LM Roman 12", 700, "normal", "lmroman12-bold.otf"),
    ("LM Roman 12", 400, "italic", "lmroman12-italic.otf"),
]

# Basic Latin, Latin-1, Latin Extended-A, common punctuation (dashes, quotes, bullets, ellipsis).
UNICODES = "U+0020-007E,U+00A0-017F,U+2010-2027,U+2030-203A,U+20AC,U+2122,U+2190-2193,U+2212"

ICONS = {
    "location": "solid/location-dot",
    "phone": "solid/phone",
    "email": "solid/envelope",
    "linkedin": "brands/square-linkedin",
    "blog": "solid/blog",
    "github": "brands/github",
    "youtube": "brands/youtube",
    "globe": "solid/globe",
}


def woff2_b64(path: Path) -> str:
    font = TTFont(path)
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["kern", "liga", "clig", "onum"]
    opts.name_IDs = ["*"]
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=subset.parse_unicodes(UNICODES))
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    return base64.b64encode(buf.getvalue()).decode()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lm-dir", type=Path, required=True)
    ap.add_argument("--fa-dir", type=Path, required=True)
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)

    css = ["/* Latin Modern Roman, GUST Font License. Subset, embedded. Generated by scripts/build_assets.py */"]
    for family, weight, style, file in FACES:
        css.append(
            f"@font-face{{font-family:'{family}';font-weight:{weight};font-style:{style};font-display:block;"
            f"src:url(data:font/woff2;base64,{woff2_b64(a.lm_dir / file)}) format('woff2');}}"
        )
    (OUT / "fonts.css").write_text("\n".join(css))

    icons = {}
    for key, rel in ICONS.items():
        svg = (a.fa_dir / f"{rel}.svg").read_text()
        icons[key] = {
            "viewBox": re.search(r'viewBox="([^"]+)"', svg).group(1),
            "path": re.search(r'<path[^>]* d="([^"]+)"', svg).group(1),
        }
    (OUT / "icons.json").write_text(json.dumps(
        {"_license": "Font Awesome Free icons, CC BY 4.0, https://fontawesome.com/license/free", **icons}, indent=1))
    print("fonts.css", round((OUT / "fonts.css").stat().st_size / 1024), "KB; icons", len(icons))


if __name__ == "__main__":
    main()
